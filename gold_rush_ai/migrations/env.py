"""Alembic environment for Auth, with no Database I/O on normal import.

Alembic 1.20.1 loads this file as ``env_py``. Only that entry point dispatches
migrations; importing ``migrations.env`` for inspection does not read env,
configure logging, create an Engine or run migrations.

Both modes require the real Auth configuration, including AUTH_CSRF_SECRET.
No .env file is loaded and no secret is generated. Run the CLI from
gold_rush_ai. Relative SQLite paths are anchored to that backend directory;
its Database parent directory must already exist. PostgreSQL online use needs
a separately installed synchronous driver and a configured AUTH_DATABASE_URL.

Autogenerated revisions remain candidates for review, especially CHECK
constraints and SQLite batch operations. Offline batch table recreation may
require an explicit copy_from table in the revision, since reflection needs
an online connection. This file does not create schema outside migrations.
"""
from __future__ import annotations

from logging.config import fileConfig
from pathlib import Path

from alembic import context
from alembic.util import CommandError
from sqlalchemy.engine import URL, make_url

from auth.config import AuthConfigError, load_auth_config
from auth.database import create_auth_engine
from auth.models import Base, ChainId, UTCDateTime


target_metadata = Base.metadata
_BACKEND_DIRECTORY = Path(__file__).resolve().parent.parent


def _database_url() -> URL:
    """Validate the full Auth snapshot without copying credentials into INI."""
    try:
        config = load_auth_config()
    except AuthConfigError as error:
        # AuthConfigError messages name fields but never include input values.
        raise CommandError(str(error)) from None
    try:
        url = make_url(config.database_url)
        supported = url.get_backend_name() in {"sqlite", "postgresql"}
        synchronous = supported and not url.get_dialect().is_async
    except Exception:
        raise CommandError("AUTH_DATABASE_URL: invalid URL or unavailable dialect.") from None
    if not supported or not synchronous:
        raise CommandError("Auth migrations require synchronous SQLite or PostgreSQL.")
    return url


def _render_item(kind, item, autogen_context):
    """Keep the application adapters in generated column declarations."""
    if kind == "type" and isinstance(item, (UTCDateTime, ChainId)):
        autogen_context.imports.add("import auth.models")
        return f"auth.models.{type(item).__name__}()"
    return False  # Use Alembic's renderer for standard SQLAlchemy objects.


def _include_object(item, name, kind, reflected, compare_to):
    # A Database may contain other applications' tables (e.g. on PostgreSQL).
    # Never propose DROP TABLE for a reflected table absent from Auth metadata.
    if kind == "table" and reflected and compare_to is None:
        return False
    return True


def _configure_options(dialect: str) -> dict:
    return {
        "target_metadata": target_metadata,
        "compare_type": True,
        "render_as_batch": dialect == "sqlite",
        "render_item": _render_item,
        "include_object": _include_object,
        "include_schemas": False,
    }


def run_migrations_offline() -> None:
    """Emit SQL without creating an Engine, loading a DBAPI driver or connecting."""
    url = _database_url()
    try:
        context.configure(
            url=url,
            literal_binds=True,
            dialect_opts={"paramstyle": "named"},
            **_configure_options(url.get_backend_name()),
        )
        with context.begin_transaction():
            context.run_migrations()
    except Exception:
        # Driver/SQLAlchemy/revision exceptions can contain URLs or parameters.
        raise CommandError("Auth offline migration failed; check configuration and revision scripts.") from None


def run_migrations_online() -> None:
    """Use the Auth Engine policy; release Connection and Engine on every exit."""
    url = _database_url()
    try:
        options = {"base_directory": _BACKEND_DIRECTORY} if url.get_backend_name() == "sqlite" else {}
        engine = create_auth_engine(database_url=url, **options)
        try:
            with engine.connect() as connection:
                context.configure(
                    connection=connection,
                    # sqlite3 autocommit=False provides transactional DDL too.
                    transactional_ddl=True,
                    **_configure_options(connection.dialect.name),
                )
                with context.begin_transaction():
                    context.run_migrations()
        finally:
            engine.dispose()
    except Exception:
        raise CommandError(
            "Auth online migration failed; check Database configuration, parent directory, "
            "synchronous driver, permissions and revision scripts."
        ) from None


def _run_environment() -> None:
    config = context.config
    if config.config_file_name is not None:
        fileConfig(config.config_file_name, disable_existing_loggers=False)
    if context.is_offline_mode():
        run_migrations_offline()
    else:
        run_migrations_online()


# Matches Alembic 1.20.1 util.load_python_file('env.py'); a normal Python import
# must stay inert even if another Alembic EnvironmentContext happens to exist.
if __name__ == "env_py":
    _run_environment()
