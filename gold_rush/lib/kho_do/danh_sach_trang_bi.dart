VatPhamHienThi _sung(
  String id,
  String ten,
  DoHiemVatPham doHiem,
  String tep,
  int satThuong,
  int tamBan, {
  bool xuyenPha = false,
}) => VatPhamHienThi(
  id: id,
  ten: ten,
  loai: LoaiVatPham.vuKhi,
  doHiem: doHiem,
  nguon: NguonVatPham.game,
  danhMuc: DanhMucVatPham.vuKhi,
  duongDanAnh: 'assets/images/trang_bi/$tep',
  satThuong: satThuong,
  tamBan: tamBan.toDouble(),
  xuyenPha: xuyenPha,
  moTa: xuyenPha
      ? 'Đạn xuyên tối đa 2 quái trên cùng đường bắn.'
      : 'Súng dùng để bắn quái theo hướng nhìn.',
  thuocTinh: {
    'Sát thương': '$satThuong HP/viên',
    'Tầm bắn': '$tamBan ô',
    if (xuyenPha) 'Xuyên mục tiêu': 'Tối đa 2 quái',
  },
);

